""" # Лабораторная работа: Аналитические вычисления с SymPy # """

import sympy as sp
from sympy import symbols, diff, integrate, solve, Matrix, series, sin, exp, oo, Eq, pprint, init_printing

# Инициализация для качественного отображения формул в Jupyter
init_printing(use_latex='mathjax')

"""
### Часть 1: Символьная алгебра

В отличие от численных библиотек, SymPy оперирует объектами `Symbol`. Это позволяет 
сохранять точность вычислений, избегая ошибок округления, свойственных `float` типу.
"""

# Объявление символов
x, y, a, b = symbols('x y a b')

# Построение выражения
expr = (x + y)**2 * (x - y)

"""
Раскрытие скобок и приведение подобных слагаемых — фундаментальные операции.
Результат: $(x + y)^2 (x - y) = x^3 - x^2y - xy^2 + y^3$
"""
expanded_expr = sp.expand(expr)
factored_expr = sp.factor(expanded_expr)

print("Раскрытое выражение:")
# display(expanded_expr)

""" # Часть 2: Математический анализ # """

"""
SymPy позволяет выполнять аналитическое дифференцирование и интегрирование.
Рассмотрим функцию $f(x) = x \sin(x) e^x$.
"""

f = x * sin(x) * exp(x)

# Вычисление первой производной
df_dx = diff(f, x)

# Вычисление неопределенного интеграла
integral_f = integrate(f, x)

print("Производная функции:")
display(df_dx)

print("Неопределенный интеграл:")
# display(integral_f)

""" # Часть 3: Решение уравнений # """

"""
Функция `solve` позволяет находить корни алгебраических уравнений, 
в том числе систем уравнений с параметрами.
"""

# Решение системы:
# 1) x + y = a
# 2) x - y = b
eq1 = Eq(x + y, a)
eq2 = Eq(x - y, b)

solution = solve((eq1, eq2), (x, y))

print("Решение системы уравнений:")
display(solution)

""" # Часть 4: Линейная алгебра # """

"""
Работа с символьными матрицами незаменима при анализе устойчивости 
или решении задач механики сплошных сред.
"""

# Матрица M с параметром
M = Matrix([[a, 1], [0, b]])

# Вычисление определителя и обратной матрицы
det_M = M.det()
inv_M = M.inv()

print("Матрица M:")
display(M)

print("Определитель матрицы:")
# display(det_M)

print("Обратная матрица M^-1:")
display(inv_M)

""" # Часть 5: Ряды и аппроксимации # """

"""
Разложение функции в ряд Тейлора позволяет аппроксимировать сложные 
трансцендентные функции полиномами в окрестности точки $x_0$.
"""

# Разложение sin(x) вокруг 0 до 6-го порядка
taylor_series = sin(x).series(x, 0, 7)

print("Разложение sin(x) в ряд Тейлора:")
display(taylor_series)

